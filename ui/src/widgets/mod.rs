//! Widget System for Continuum Studio
//!
//! Modular UI components that communicate via events.
//! Each widget is independent and can be composed into layouts.

pub mod diagram;
pub mod code_view;
pub mod terminal;
pub mod tab_bar;

use eframe::egui::Ui;
use anyhow::Result;

// Re-exports
pub use diagram::{DiagramWidget, DiagramNode, DiagramEdge, NodeShape, NodeStatus, ArrowType, DiagramTheme};
pub use code_view::{CodeViewWidget, CodeTheme, Language};
pub use terminal::{TerminalWidget, TerminalTheme, AnsiColor, TerminalLine};
